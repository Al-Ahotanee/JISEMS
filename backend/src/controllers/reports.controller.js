const { pool } = require('../config/database');
const ApiResponse = require('../utils/response');
const logger = require('../utils/logger');
const PDFDocument = require('pdfkit');


const generatePDF = async (req, res) => {
  try {
    const { election_id, lga_id } = req.query;
    const [elections] = await pool.query(
      election_id ? 'SELECT id, title, election_date, status FROM elections WHERE id = ?' : "SELECT id, title, election_date, status FROM elections WHERE status = 'ongoing' LIMIT 1",
      election_id ? [parseInt(election_id)] : []
    );
    if (!elections.length) return ApiResponse.notFound(res, 'No election found');
    const election = elections[0];

    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=JISEMS-Report-${Date.now()}.pdf`);
    doc.pipe(res);

    // Header
    doc.fontSize(24).font('Helvetica-Bold').fillColor('#1e3a8a').text('JISEMS', { align: 'center' });
    doc.fontSize(10).font('Helvetica').fillColor('#666').text('Jigawa State Election Monitor', { align: 'center' });
    doc.moveDown();
    doc.fontSize(16).font('Helvetica-Bold').fillColor('#000').text(election.title, { align: 'center' });
    doc.fontSize(10).text(`Election Date: ${election.election_date} | Status: ${election.status}`, { align: 'center' });
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke('#1a5632');
    doc.moveDown();

    // Candidate Results
    doc.fontSize(14).font('Helvetica-Bold').text('Candidate Results');
    doc.moveDown(0.5);

    const [candidates] = await pool.query(
      `SELECT c.full_name, c.party_code, c.party_name,
              COALESCE(SUM(CASE WHEN rs.id IS NOT NULL THEN vd.votes ELSE 0 END), 0) AS total_votes
       FROM candidates c
       LEFT JOIN vote_data vd ON vd.candidate_id = c.id
       LEFT JOIN result_submissions rs ON rs.id = vd.submission_id AND rs.status = 'verified' AND rs.election_id = ?
       WHERE c.election_id = ? GROUP BY c.id ORDER BY total_votes DESC`,
      [election.id, election.id]
    );
    const totalVotes = candidates.reduce((s, c) => s + Number(c.total_votes), 0);

    candidates.forEach(c => {
      const pct = totalVotes > 0 ? ((Number(c.total_votes) / totalVotes) * 100).toFixed(1) : '0.0';
      doc.fontSize(11).font('Helvetica-Bold').text(`${c.full_name} (${c.party_code})`);
      doc.fontSize(10).font('Helvetica').text(`${Number(c.total_votes).toLocaleString()} votes (${pct}%)`);
      doc.moveDown(0.3);
    });

    doc.moveDown();

    // LGA Summary
    doc.fontSize(14).font('Helvetica-Bold').text('LGA Summary');
    doc.moveDown(0.5);

    let lgaFilter = '';
    const lgaParams = [election.id, election.id];
    if (lga_id) { lgaFilter = ' AND l.id = ?'; lgaParams.push(parseInt(lga_id)); }

    const [lgaSummary] = await pool.query(
      `SELECT l.name, 
              (SELECT COUNT(*) FROM polling_units WHERE lga_id = l.id) as total_pus,
              (SELECT COUNT(*) FROM result_submissions WHERE lga_id = l.id AND election_id = ? AND status <> 'rejected') AS reported,
              (SELECT COUNT(*) FROM result_submissions WHERE lga_id = l.id AND election_id = ? AND status = 'verified') as verified
       FROM lgas l WHERE 1=1 ${lgaFilter} ORDER BY l.name`,
      lgaParams
    );

    // Table header
    const tableTop = doc.y;
    doc.fontSize(9).font('Helvetica-Bold');
    doc.text('LGA', 50, tableTop, { width: 120 });
    doc.text('Total PUs', 170, tableTop, { width: 80, align: 'center' });
    doc.text('Reported', 250, tableTop, { width: 80, align: 'center' });
    doc.text('Verified', 330, tableTop, { width: 80, align: 'center' });
    doc.text('Progress', 410, tableTop, { width: 80, align: 'center' });
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke('#ccc');

    doc.font('Helvetica').fontSize(9);
    lgaSummary.forEach(lga => {
      const y = doc.y + 5;
      if (y > 700) { doc.addPage(); }
      const pct = lga.total_pus > 0 ? ((lga.reported / lga.total_pus) * 100).toFixed(1) : '0.0';
      doc.text(lga.name, 50, doc.y + 3, { width: 120 });
      doc.text(String(lga.total_pus), 170, doc.y - 12, { width: 80, align: 'center' });
      doc.text(String(lga.reported), 250, doc.y - 12, { width: 80, align: 'center' });
      doc.text(String(lga.verified), 330, doc.y - 12, { width: 80, align: 'center' });
      doc.text(`${pct}%`, 410, doc.y - 12, { width: 80, align: 'center' });
    });

    doc.moveDown(2);
    doc.fontSize(8).fillColor('#999').text(`Generated by JISEMS on ${new Date().toISOString()}`, { align: 'center' });
    doc.text('Counting Every Vote. Protecting Every Voice.', { align: 'center' });

    doc.end();
  } catch (error) {
    logger.error('PDF generation error:', error);
    return ApiResponse.error(res, 'Failed to generate PDF');
  }
};

const generateExcel = async (req, res) => {
  try {
    const { election_id, lga_id } = req.query;
    const [elections] = await pool.query(
      election_id ? 'SELECT id, title, election_date, status FROM elections WHERE id = ?' : "SELECT id, title, election_date, status FROM elections WHERE status = 'ongoing' LIMIT 1",
      election_id ? [parseInt(election_id)] : []
    );
    if (!elections.length) return ApiResponse.notFound(res, 'No election found');
    const election = elections[0];

    const { default: writeExcelFile } = await import('write-excel-file/node');

    let resultsQuery = `SELECT rs.submission_uid, pu.name AS pu_name, w.name AS ward_name, l.name AS lga_name,
                               rs.status, rs.accredited_voters, rs.total_votes_cast, rs.rejected_votes, rs.created_at
                        FROM result_submissions rs
                        JOIN polling_units pu ON pu.id = rs.polling_unit_id
                        JOIN wards w ON w.id = rs.ward_id
                        JOIN lgas l ON l.id = rs.lga_id
                        WHERE rs.election_id = ? AND rs.status = 'verified'`;
    const params = [election.id];
    if (lga_id) { resultsQuery += ' AND rs.lga_id = ?'; params.push(parseInt(lga_id, 10)); }
    resultsQuery += ' ORDER BY l.name, w.name, pu.name';
    const [results] = await pool.query(resultsQuery, params);

    const resultRows = [
      ['Submission UID', 'Polling Unit', 'Ward', 'LGA', 'Status', 'Accredited', 'Total Votes', 'Rejected', 'Submitted At'],
      ...results.map((r) => [
        r.submission_uid, r.pu_name, r.ward_name, r.lga_name, r.status,
        Number(r.accredited_voters || 0), Number(r.total_votes_cast || 0), Number(r.rejected_votes || 0),
        r.created_at ? new Date(r.created_at).toISOString() : ''
      ])
    ];

    const [candidates] = await pool.query(
      `SELECT c.full_name, c.party_code,
              COALESCE(SUM(CASE WHEN rs.id IS NOT NULL THEN vd.votes ELSE 0 END), 0) AS total_votes
       FROM candidates c
       LEFT JOIN vote_data vd ON vd.candidate_id = c.id
       LEFT JOIN result_submissions rs ON rs.id = vd.submission_id AND rs.status = 'verified' AND rs.election_id = ?
       WHERE c.election_id = ? GROUP BY c.id ORDER BY total_votes DESC`,
      [election.id, election.id]
    );
    const totalVotes = candidates.reduce((sum, candidate) => sum + Number(candidate.total_votes), 0);
    const candidateRows = [
      ['Candidate', 'Party', 'Total Votes', 'Percentage'],
      ...candidates.map((candidate) => [
        candidate.full_name,
        candidate.party_code,
        Number(candidate.total_votes),
        totalVotes > 0 ? `${((Number(candidate.total_votes) / totalVotes) * 100).toFixed(2)}%` : '0%'
      ])
    ];

    const [lgaData] = await pool.query(
      `SELECT l.name,
              (SELECT COUNT(*) FROM polling_units WHERE lga_id = l.id) AS total,
              (SELECT COUNT(*) FROM result_submissions WHERE lga_id = l.id AND election_id = ? AND status <> 'rejected') AS reported,
              (SELECT COUNT(*) FROM result_submissions WHERE lga_id = l.id AND election_id = ? AND status = 'verified') AS verified
       FROM lgas l ORDER BY l.name`,
      [election.id, election.id]
    );
    const lgaRows = [
      ['LGA', 'Total PUs', 'Reported', 'Verified', 'Progress'],
      ...lgaData.map((lga) => [
        lga.name,
        Number(lga.total || 0),
        Number(lga.reported || 0),
        Number(lga.verified || 0),
        Number(lga.total || 0) > 0 ? `${((Number(lga.reported || 0) / Number(lga.total)) * 100).toFixed(1)}%` : '0%'
      ])
    ];

    const workbook = await writeExcelFile([
      { sheet: 'Results', data: resultRows },
      { sheet: 'Candidates', data: candidateRows },
      { sheet: 'LGA Summary', data: lgaRows }
    ]).toBuffer();

    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', `attachment; filename=JISEMS-Report-${Date.now()}.xlsx`);
    return res.send(workbook);
  } catch (error) {
    logger.error('Excel generation error:', error);
    return ApiResponse.error(res, 'Failed to generate Excel');
  }
};

function escapeCsvCell(val) {
  if (val === null || val === undefined) return '""';
  let str = String(val);
  if (/^[=+\-@\t\r]/.test(str)) {
    str = `'${str}`;
  }
  return `"${str.replace(/"/g, '""')}"`;
}

const generateCSV = async (req, res) => {
  try {
    const { election_id } = req.query;
    const [elections] = await pool.query(
      election_id ? 'SELECT id, title, election_date, status FROM elections WHERE id = ?' : "SELECT id, title, election_date, status FROM elections WHERE status = 'ongoing' LIMIT 1",
      election_id ? [parseInt(election_id)] : []
    );
    if (!elections.length) return ApiResponse.notFound(res, 'No election found');

    const [results] = await pool.query(
      `SELECT rs.submission_uid, pu.name as pu_name, pu.inec_pu_code, w.name as ward_name, l.name as lga_name,
              rs.status, rs.accredited_voters, rs.total_valid_votes, rs.rejected_votes, rs.total_votes_cast,
              rs.latitude, rs.longitude, rs.created_at,
              CONCAT(u.first_name, ' ', u.last_name) as submitted_by
       FROM result_submissions rs
       JOIN polling_units pu ON pu.id = rs.polling_unit_id
       JOIN wards w ON w.id = rs.ward_id
       JOIN lgas l ON l.id = rs.lga_id
       JOIN users u ON u.id = rs.submitted_by
       WHERE rs.election_id = ? AND rs.status = 'verified' ORDER BY l.name, w.name`,
      [elections[0].id]
    );

    const headers = 'Submission UID,Polling Unit,PU Code,Ward,LGA,Status,Accredited,Valid Votes,Rejected,Total Cast,Latitude,Longitude,Submitted At,Submitted By\n';
    const rows = results.map(r =>
      [
        escapeCsvCell(r.submission_uid),
        escapeCsvCell(r.pu_name),
        escapeCsvCell(r.inec_pu_code),
        escapeCsvCell(r.ward_name),
        escapeCsvCell(r.lga_name),
        escapeCsvCell(r.status),
        Number(r.accredited_voters || 0),
        Number(r.total_valid_votes || 0),
        Number(r.rejected_votes || 0),
        Number(r.total_votes_cast || 0),
        r.latitude || '',
        r.longitude || '',
        escapeCsvCell(r.created_at ? new Date(r.created_at).toISOString() : ''),
        escapeCsvCell(r.submitted_by)
      ].join(',')
    ).join('\n');

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename=JISEMS-Results-${Date.now()}.csv`);
    res.send(headers + rows);
  } catch (error) {
    logger.error('CSV generation error:', error);
    return ApiResponse.error(res, 'Failed to generate CSV');
  }
};

module.exports = { generatePDF, generateExcel, generateCSV };
